#!/usr/bin/env python3
"""
Benchmark + correctness-check the in-tree P-256 ecdsa_verify on a real
Ultimate 64 Elite, at 48 MHz turbo (primary) and optionally 1 MHz.

Drives the UCI-build PRG, boots it to the main_loop, quits to BASIC,
DMA-injects a 6502 stub at $4200 that:

  1. Banks out BASIC ROM so the ECDSA data buffers at $B0xx are RAM-visible.
  2. Writes a "running" sentinel ($AA) at $4540.
  3. Calls ecdsa_verify.
  4. PHP/PLA-captures the P register into $4542 (bit 0 = carry).
  5. Writes a "done" sentinel ($55) at $4541.
  6. Parks.

The host pre-loads pubkey_x/y, hash, sig_r, sig_s, sig_len=32, hash_len=32,
curve_id=0 into the ecdsa_* buffers via DMA, then triggers the stub and
polls the done-sentinel with wall-clock timing around the *transition*
from running->done. That gives us the on-device wall-clock for the
verify call itself, not the SYS-dispatch or keyboard plumbing.

The test vectors come from tools/uci/_ecdsa_vectors.json (generated by
_ecdsa_vectors.py). Set ECDSA_VECTORS_JSON to override the path.

Env:
  U64_HOST         — default 192.168.1.81
  ECDSA_MHZ_LIST   — comma list, default "48"; include "1" for a 1 MHz
                     baseline (expect 10-30 min at 1 MHz).
  ECDSA_REPEATS    — repeats per vector at each speed; default 3 for
                     positive, 1 for negative.
  ECDSA_POLL_S     — poll interval (s) for done-sentinel; default 0.10.
  ECDSA_TIMEOUT_S  — per-run timeout. Default 180s at 48 MHz,
                     2400s at 1 MHz.
  ECDSA_DEBUG_CAPTURE — "1" to enable U64 6510 debug-stream capture for
                     the FIRST 48 MHz positive run; artifacts written
                     under $ECDSA_DEBUG_DIR (default /tmp/ecdsa_debug/).
  KEEP_DEBUG_ON_PASS — as in test_https_local.py.
"""
